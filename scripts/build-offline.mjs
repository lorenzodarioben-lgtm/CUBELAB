import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../dist/', import.meta.url));

async function filesIn(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries.map((entry) => entry.isDirectory() ? filesIn(join(dir, entry.name)) : [join(dir, entry.name)]));
  return nested.flat();
}

const files = (await filesIn(root)).filter((file) => !file.endsWith(`${sep}sw.js`)).sort();
const urls = files.map((file) => `/${relative(root, file).split(sep).join('/')}`);
const hash = createHash('sha256');
for (const file of files) {
  hash.update(relative(root, file));
  hash.update(await readFile(file));
}
const version = hash.digest('hex').slice(0, 12);
const source = `/* Generated by scripts/build-offline.mjs — every production asset is available offline. */
const CACHE_NAME = 'cubelab-offline-${version}';
const CACHE_PREFIX = 'cubelab-offline-';
const ASSETS = ${JSON.stringify(['/', ...urls])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(ASSETS)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(async () => (await caches.match('/index.html')) ?? Response.error()));
    return;
  }
  event.respondWith(caches.match(new URL(request.url).pathname, { ignoreVary: true }).then((cached) => cached ?? fetch(request)));
});
`;
await writeFile(join(root, 'sw.js'), source);
console.log(`Offline cache ${version}: ${urls.length} assets`);
